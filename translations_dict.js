window.getAllTranslatableTextNodes = function () {
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: function (node) {
      if (!node.parentElement) return NodeFilter.FILTER_REJECT;
      var tag = node.parentElement.tagName;
      if (
        tag === "SCRIPT" ||
        tag === "STYLE" ||
        tag === "NOSCRIPT" ||
        tag === "OPTION"
      ) {
        return NodeFilter.FILTER_REJECT;
      }
      if (node.parentElement.closest("#settingsModal")) {
        return NodeFilter.FILTER_REJECT;
      }
      var trimmed = node.nodeValue.trim();
      if (!trimmed || /^[\d\s\$\€\£\+\-\(\)\/\:\.\,\%\#\•\|]+$/.test(trimmed)) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  var nodes = [];
  var current;
  while ((current = walker.nextNode())) {
    nodes.push(current);
  }
  return nodes;
};

window.translateSingleText = async function (originalText, langCode) {
  var familyCode = window.DIALECT_FAMILY_MAP[langCode] || langCode;
  var dict =
    window.PEARL_TRAILS_DICT[langCode] ||
    window.PEARL_TRAILS_DICT[familyCode] ||
    {};
  var cleanKey = originalText.replace(/\s+/g, " ").trim();

  if (dict[cleanKey]) {
    return dict[cleanKey];
  }

  var colonIdx = cleanKey.indexOf(":");
  if (colonIdx > 0) {
    var prefix = cleanKey.slice(0, colonIdx).trim();
    var rest = cleanKey.slice(colonIdx + 1).trim();
    if (dict[prefix]) {
      return dict[prefix] + ": " + rest;
    }
  }

  var cacheKey = "pt_v2_" + langCode + "_" + cleanKey;
  var cached = localStorage.getItem(cacheKey);
  if (cached) {
    return cached;
  }

  var targetIso = window.CLOUD_ISO_MAP[langCode] || "sw";
  if (targetIso === "en" || cleanKey.length > 500) {
    return originalText;
  }

  try {
    var url =
      "https://googleapis.com" +
      encodeURIComponent(targetIso) +
      "&dt=t&q=" +
      encodeURIComponent(cleanKey);
    var res = await fetch(url);
    var data = await res.json();
    if (data && Array.isArray(data) && Array.isArray(data[0])) {
      var translated = "";
      for (var i = 0; i < data[0].length; i++) {
        if (data[0][i] && data[0][i][0]) {
          translated += data[0][i][0];
        }
      }
      if (translated.trim() !== "") {
        localStorage.setItem(cacheKey, translated);
        return translated;
      }
    }
  } catch (e) {
    var words = cleanKey.split(" ");
    var replaced = words
      .map(function (w) {
        return dict[w] || w;
      })
      .join(" ");
    return replaced;
  }

  return originalText;
};

window.translateWholeSystem = async function (langCode) {
  if (!langCode || langCode === "en") return;

  var textNodes = window.getAllTranslatableTextNodes();
  var batchSize = 15;

  for (var i = 0; i < textNodes.length; i += batchSize) {
    var batch = textNodes.slice(i, i + batchSize);
    await Promise.all(
      batch.map(async function (node) {
        if (!node._origValue) {
          node._origValue = node.nodeValue;
        }
        var leadingSpace = node._origValue.match(/^\s*/)[0];
        var trailingSpace = node._origValue.match(/\s*$/)[0];
        var coreText = node._origValue.trim();

        var translatedCore = await window.translateSingleText(
          coreText,
          langCode,
        );
        node.nodeValue = leadingSpace + translatedCore + trailingSpace;
      }),
    );
  }

  var inputs = document.querySelectorAll(
    "input[placeholder], textarea[placeholder]",
  );
  await Promise.all(
    Array.from(inputs).map(async function (inp) {
      if (!inp.dataset.origPlaceholder) {
        inp.dataset.origPlaceholder = inp.placeholder;
      }
      inp.placeholder = await window.translateSingleText(
        inp.dataset.origPlaceholder,
        langCode,
      );
    }),
  );
};
